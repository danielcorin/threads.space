// Threads echo bot — reference implementation, typed against the OpenAPI spec.
//
// Two integration surfaces:
//   1. WebSocket  GET /ws/:channelId        — receive live channel events, and send
//      lightweight signals (typing_start/typing_stop, ping). One socket per channel.
//   2. REST       POST /messages/:id/replies, /messages/:id/reactions,
//      /channels/:id/read, /bots/self/capabilities; GET /channels, /dms — create
//      durable state and discover where to listen.
//
// Request/response shapes are imported from the generated spec types (see the `import
// type` block) so a wrong field name or message_type fails `npm run typecheck`. The bot
// is *run* with tsx, which strips types without checking — so `npm start` works even
// before the (gitignored) generated types exist; only `npm run typecheck` needs them.
//
// Run with: npm start   (env loaded from ../.env). See .env.example for the required
// variables.
