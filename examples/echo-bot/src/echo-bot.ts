// --- Spec types -------------------------------------------------------------
// Generated by `npm run gen-types` (openapi-typescript) from api/openapi/*.yaml.
// These are type-only imports: tsx erases them at runtime, so a missing file only
// breaks `npm run typecheck`, never `npm start`.
import type { components } from '../../../api/generated/types/threads';
import type { components as WsComponents } from '../../../api/generated/types/ws-events';

type Schemas = components['schemas'];
type WsSchemas = WsComponents['schemas'];

// REST request/response bodies, straight from the spec.
type SendMessageRequest = Schemas['SendMessageRequest'];
type AddReactionRequest = Schemas['AddReactionRequest'];
type UpdateSelfCapabilitiesRequest = Schemas['UpdateSelfCapabilitiesRequest'];
type Message = Schemas['Message'];
type MessageType = Schemas['MessageType'];
type ChannelListItem = Schemas['ChannelListItem'];
type DMChannel = Schemas['DMChannel'];

// WebSocket events. Caveat: openapi-typescript rewrites each event's `type` to the
// *schema name* ("MessageEvent") as a synthetic discriminator, but the value actually
// on the wire is the OpenAPI `const` ("message"). Re-map the events we narrow on so the
// runtime check (`type === 'message'`) and the static type agree. `Wire<S, T>` does the
// remap: take the generated schema S, drop its bogus discriminator, pin the real one.
type Wire<S, T extends string> = Omit<S, 'type'> & { type: T };
type MessageEvent = Wire<WsSchemas['MessageEvent'], 'message'>;
type ReactionAddedEvent = Wire<WsSchemas['ReactionAddedEvent'], 'reaction_added'>;
type MemberAddedEvent = Wire<WsSchemas['MemberAddedEvent'], 'member_added'>;
type MemberRemovedEvent = Wire<WsSchemas['MemberRemovedEvent'], 'member_removed'>;
type ChannelArchivedEvent = Wire<WsSchemas['ChannelArchivedEvent'], 'channel_archived'>;
type ChannelDeletedEvent = Wire<WsSchemas['ChannelDeletedEvent'], 'channel_deleted'>;
// The yaml schema is named `removed_event`; its `const` type is bot_restart_requested.
type RestartRequestedEvent = Wire<WsSchemas['removed_event'], 'bot_restart_requested'>;
// Cooperative cancellation: Threads emits this (over WS *and* webhook) when a human
// cancels a process this bot created. The bot is expected to stop the matching run.
type ProcessKillEvent = Wire<WsSchemas['ProcessKillEvent'], 'process_kill'>;
type ActionResultEvent = Wire<WsSchemas['ActionResultEvent'], 'action_result'>;
type ActionErrorEvent = Wire<WsSchemas['ActionErrorEvent'], 'action_error'>;
// Presence socket (GET /ws/presence) events.
type PresenceSnapshotEvent = Wire<WsSchemas['PresenceSnapshotEvent'], 'presence_snapshot'>;
type PresenceUpdateEvent = Wire<WsSchemas['PresenceUpdateEvent'], 'presence_update'>;

// Outbound socket signals. We hand-write these unions rather than reuse the generated
// *ClientEvent* types for the same discriminator reason: their `type` is rewritten to
// the schema name, not the wire value.
//   - signals are fire-and-forget (no reply expected);
//   - actions carry an actionId and are answered with action_result / action_error.
type WsSignal = { type: 'typing_start' } | { type: 'typing_stop' } | { type: 'ping' };
type WsActionRequest =
  | { type: 'reaction.add'; messageId: string; emoji: string }
  | { type: 'message.create'; channelId: string; content: string; threadId?: string | null; message_type?: MessageType };

