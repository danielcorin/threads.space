const EXPLICIT_CHANNELS = (process.env.THREADS_CHANNEL_IDS ?? process.env.THREADS_CHANNEL_ID ?? '')
  .split(',')
  .map((s) => s.trim())
  .filter(Boolean);

const WS_BASE = API_URL.replace(/^http/, 'ws'); // https→wss, http→ws
const AUTH = { Authorization: `Bearer ${BOT_TOKEN}` };

// How often to re-discover channels/DMs, so the bot picks up a channel it was just
// added to or a DM a human just opened (neither arrives on a socket it already holds).
const DISCOVERY_INTERVAL_MS = 30_000;

// Remember message ids we have already acted on. Reconnects re-deliver nothing,
// but a defensive dedup set keeps us idempotent if the bot is restarted mid-stream.
const handled = new Set<string>();

// Ids of messages this bot authored, so it can tell when a human reacts to *its* output
// (the reaction-mirror trigger). Both this and `handled` grow unbounded; a long-running
// bot would cap them (e.g. an LRU) — fine to keep simple for a reference.
const myMessages = new Set<string>();

// --- Process runs -----------------------------------------------------------
// A "process" is one turn this bot is working on. The bot creates it (POST /processes)
// when it starts, reports activity/status over REST, and finishes it as done — UNLESS a
// human cancels it from Threads, which arrives as a process_kill event (over the channel
// WebSocket and, if configured, the webhook receiver below). On cancel we flip
// `cancelled` and wake the in-flight wait so the turn stops without posting an answer.
interface InflightRun {
  processId: string;
  channelId: string;
  cancelled: boolean;
  wake: () => void; // resolves the current abortable wait early
}
const runs = new Map<string, InflightRun>(); // processId -> run

function markCancelled(processId: string): void {
  const run = runs.get(processId);
  if (!run || run.cancelled) return;
  run.cancelled = true;
  run.wake();
  console.log(`[proc] cancel received for ${processId}`);
}

// sleep that returns early if the run is cancelled. Resolves true if it slept the full
// duration, false if it was woken by a cancel.
function abortableSleep(ms: number, run: InflightRun | null): Promise<boolean> {
  return new Promise((resolve) => {
    if (run?.cancelled) return resolve(false);
    const timer = setTimeout(() => resolve(true), ms);
    if (run) {
      run.wake = () => {
        clearTimeout(timer);
        resolve(false);
      };
    }
  });
}

// --- REST helper ------------------------------------------------------------
// Every REST call carries the bot's Bearer token. Returns the parsed JSON body typed
// as T, or throws with the status + body text so callers can log a useful error.
async function api<T = unknown>(method: string, path: string, body?: unknown): Promise<T> {
  const res = await fetch(`${API_URL}${path}`, {
    method,
    headers: { ...AUTH, ...(body !== undefined ? { 'Content-Type': 'application/json' } : {}) },
    body: body !== undefined ? JSON.stringify(body) : undefined,
  });
  if (!res.ok) {
    throw new Error(`${method} ${path} → ${res.status} ${await res.text()}`);
  }
  // Some endpoints (mark-read) return an empty body; tolerate that.
  return (res.status === 204 ? null : await res.json().catch(() => null)) as T;
}

